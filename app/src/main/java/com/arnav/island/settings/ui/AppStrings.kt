package com.arnav.island.settings.ui

import androidx.compose.runtime.Composable
import androidx.compose.runtime.compositionLocalOf
import com.arnav.island.storage.AppLanguage

val LocalAppLanguage = compositionLocalOf { AppLanguage.VIETNAMESE }

@Composable
fun tr(en: String, vi: String): String =
    if (LocalAppLanguage.current == AppLanguage.VIETNAMESE) vi else en

@Composable
fun tr(text: String): String = translate(text, LocalAppLanguage.current)

fun translate(text: String, lang: AppLanguage): String {
    if (lang == AppLanguage.ENGLISH || text.isEmpty()) return text
    DICT[text]?.let { return it }

    // Dynamic prefix/pattern translations
    if (text.startsWith("Running · hidden (") && text.endsWith(")")) {
        val reason = text.removePrefix("Running · hidden (").removeSuffix(")")
        return "Đang chạy · tạm ẩn ($reason)"
    }
    if (text.startsWith("Running · ")) {
        val profile = text.removePrefix("Running · ")
        return "Đang chạy · $profile"
    }
    if (text.startsWith("Version ") && text.contains(" · play every feature")) {
        val v = text.substringAfter("Version ").substringBefore(" ·")
        return "Phiên bản $v · trải nghiệm mọi tính năng"
    }
    if (text.startsWith("Version ") && text.contains(" · Galaxy Z Flip5 Edition")) {
        val v = text.substringAfter("Version ").substringBefore(" ·")
        return "Phiên bản $v · Bản chuẩn Galaxy Z Flip5 (One UI 9)"
    }
    if (text.endsWith(" animation") && !text.startsWith("Charging")) {
        val prefix = text.removeSuffix(" animation")
        return "Hiệu ứng ${DICT[prefix] ?: prefix}"
    }
    if (text.startsWith("Test charging (") && text.endsWith(")")) {
        val inner = text.removePrefix("Test charging (").removeSuffix(")")
        return "Thử hiệu ứng sạc (${DICT[inner] ?: inner})"
    }
    if (text.startsWith("A countdown ") && text.contains(" min before events in your calendars.")) {
        val mins = text.substringAfter("A countdown ").substringBefore(" min")
        return "Đếm ngược $mins phút trước sự kiện lịch của bạn. Sẽ hỏi quyền truy cập lịch."
    }
    if (text.startsWith("Your animation scale is ") && text.contains("(Developer options)")) {
        val scale = text.substringAfter("Your animation scale is ").substringBefore(" (")
        return "Tỷ lệ hoạt ảnh hiện tại là $scale (Tùy chọn nhà phát triển). Đảo sẽ nhanh/chậm theo hệ thống."
    }
    if (text.startsWith("Right now One UI pop-ups are ")) {
        val off = text.contains("off (BreezeIsland")
        return if (off) {
            "Hiện tại thông báo nổi One UI đang tắt (BreezeIsland đảm nhận hiển thị). Chúng sẽ tự bật lại khi đảo ẩn, khóa màn hình hoặc dừng ứng dụng."
        } else {
            "Hiện tại thông báo nổi One UI đang bật. Chúng sẽ tự bật lại bất cứ khi nào đảo ẩn, khóa màn hình hoặc dừng BreezeIsland."
        }
    }
    if (text.startsWith("Compact ") && text.contains(" · Expanded ")) {
        return text
            .replace("Compact ", "Thu gọn ")
            .replace("Expanded ", "Mở rộng ")
            .replace(" wide", " rộng")
    }
    if (text.endsWith(" min") && text.substringBefore(" min").all { it.isDigit() }) {
        return text.replace(" min", " phút")
    }
    if (text.startsWith("Lap ")) {
        return text.replace("Lap ", "Vòng ")
    }
    if (text.startsWith("Island ")) {
        return text.replace("Island ", "BreezeIsland ")
    }
    if (text.endsWith(" · this version")) {
        val prefix = text.removeSuffix(" · this version")
        return "${DICT[prefix] ?: prefix} · phiên bản hiện tại"
    }
    return text
}

